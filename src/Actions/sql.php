<?php

function lanter_action_sql(Lanter_Config $config, Lanter_Auth $auth, ?array $connection): void
{
    $driver = lanter_make_driver($connection);

    $sql = trim((string) ($_POST['sql'] ?? $_GET['sql'] ?? ''));
    $results = [];
    $error = null;
    $elapsedMs = null;
    $readOnly = lanter_is_read_only($connection);

    if ($sql === '' && $_SERVER['REQUEST_METHOD'] !== 'POST' && ($_GET['template'] ?? '') === 'create_table') {
        $sql = match (lanter_driver_kind($connection)) {
            'sqlite' => "CREATE TABLE table_name (\n    id INTEGER PRIMARY KEY AUTOINCREMENT,\n    name TEXT NOT NULL\n);",
            'pgsql' => "CREATE TABLE table_name (\n    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n    name TEXT NOT NULL\n);",
            default => "CREATE TABLE table_name (\n    id INT AUTO_INCREMENT PRIMARY KEY,\n    name VARCHAR(255) NOT NULL\n);",
        };
    }

    if ($_SERVER['REQUEST_METHOD'] === 'POST' && $sql !== '') {
        $statements = lanter_split_sql($sql);
        $start = microtime(true);

        foreach ($statements as $statement) {
            if ($readOnly && !lanter_sql_is_read_only($statement)) {
                $error = 'This connection is read-only; only SELECT-style statements are allowed.';
                break;
            }

            try {
                $results[] = ['sql' => $statement, 'result' => $driver->runQuery($statement)];
            } catch (Throwable $e) {
                $error = $e->getMessage();
                $results[] = ['sql' => $statement, 'result' => null];
                break;
            }
        }

        $elapsedMs = round((microtime(true) - $start) * 1000, 2);
        lanter_sql_history_push($config, $sql);
    }

    $tables = $driver->listTables();
    $views = $driver->listViews();
    $content = lanter_render_sql_console($sql, $results, $error, $elapsedMs, lanter_sql_history(), $readOnly);

    lanter_render_layout('SQL Console', $content, $tables, null, lanter_table_counts($driver, $tables), $views);
}

/** Re-runs a single SELECT and streams the result as CSV or JSON. */
function lanter_action_sql_export(Lanter_Config $config, Lanter_Auth $auth, ?array $connection): void
{
    if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
        lanter_redirect('sql');
    }

    $sql = trim((string) ($_POST['sql'] ?? ''));
    $format = ($_POST['format'] ?? 'csv') === 'json' ? 'json' : 'csv';

    if ($sql === '' || !lanter_sql_is_read_only($sql)) {
        lanter_redirect('sql');
    }

    $driver = lanter_make_driver($connection);
    $result = $driver->runQuery($sql);
    $filename = 'query-' . date('Ymd-His') . '.' . $format;

    if ($format === 'json') {
        header('Content-Type: application/json; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        echo json_encode($result['rows'], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE);

        throw new Lanter_Halt();
    }

    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    $out = fopen('php://output', 'w');
    fputcsv($out, $result['columns'], ',', '"', '\\', "\n");

    foreach ($result['rows'] as $row) {
        fputcsv($out, array_map(static fn ($v): string => $v === null ? '' : (string) $v, $row), ',', '"', '\\', "\n");
    }

    fclose($out);

    throw new Lanter_Halt();
}

/** @return string[] */
function lanter_sql_history(): array
{
    return $_SESSION['lanter_sql_history'] ?? [];
}

function lanter_sql_history_push(Lanter_Config $config, string $sql): void
{
    $limit = $config->sqlHistorySize();

    if ($limit === 0) {
        return;
    }

    $history = array_values(array_filter(lanter_sql_history(), static fn (string $item): bool => $item !== $sql));
    array_unshift($history, $sql);
    $_SESSION['lanter_sql_history'] = array_slice($history, 0, $limit);
}

/**
 * @param array<int, array{sql: string, result: ?array{columns: string[], rows: array<int, array<string, mixed>>, affected: int}}> $results
 * @param string[] $history
 */
function lanter_render_sql_console(string $sql, array $results, ?string $error, ?float $elapsedMs, array $history, bool $readOnly): string
{
    $sqlEscaped = htmlspecialchars($sql);
    $terminalIcon = lanter_icon('terminal');
    $runIcon = lanter_icon('play');
    $csrf = lanter_csrf_field();
    $readOnlyHint = $readOnly ? '<span class="lanter-badge lanter-badge-amber">read-only</span>' : '';

    $historyHtml = '';
    if ($history !== []) {
        $items = '';
        foreach ($history as $item) {
            $preview = mb_substr(preg_replace('/\s+/', ' ', $item), 0, 90);
            $items .= '<button type="button" class="lanter-history-item" data-sql="' . htmlspecialchars($item) . '" title="Load into editor">'
                . htmlspecialchars($preview) . (mb_strlen($item) > 90 ? '…' : '') . '</button>';
        }

        $historyHtml = '<details class="lanter-details lanter-history"><summary>History (' . count($history) . ')</summary><div class="lanter-history-list">' . $items . '</div></details>';
    }

    $form = <<<HTML
        <form class="lanter-sql-form" method="post" action="?action=sql" id="lanter-sql-form">
            {$csrf}
            <div class="lanter-sql-console">
                <div class="lanter-sql-console-head">
                    <span>{$terminalIcon}<span>query.sql</span>{$readOnlyHint}</span>
                    <span class="lanter-sql-shortcut"><kbd>Ctrl</kbd> + <kbd>Enter</kbd></span>
                </div>
                <textarea class="lanter-sql-editor" name="sql" id="lanter-sql-editor" rows="8" placeholder="SELECT * FROM ... (several statements separated by ; are fine)" spellcheck="false">{$sqlEscaped}</textarea>
                <div class="lanter-sql-actions">
                    <button class="lanter-btn" type="submit">{$runIcon}<span>Run</span></button>
                </div>
            </div>
        </form>
        {$historyHtml}
        <script>
            (function () {
                var editor = document.getElementById('lanter-sql-editor');
                var form = document.getElementById('lanter-sql-form');
                if (!editor || !form) { return; }

                var destructive = /^\\s*(drop|truncate|alter|delete\\s+from\\s+\\S+\\s*;?\\s*$|update\\s+\\S+\\s+set\\b(?![\\s\\S]*\\bwhere\\b))/i;

                form.addEventListener('submit', function (event) {
                    var statements = editor.value.split(';');
                    var risky = statements.filter(function (s) { return destructive.test(s); });
                    if (risky.length && !confirm('This will run a destructive statement (DROP, TRUNCATE, ALTER or an unfiltered DELETE/UPDATE). Continue?')) {
                        event.preventDefault();
                    }
                });

                editor.addEventListener('keydown', function (event) {
                    if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') {
                        event.preventDefault();
                        form.requestSubmit();
                    }
                });

                document.addEventListener('click', function (event) {
                    var item = event.target.closest('.lanter-history-item');
                    if (!item) { return; }
                    editor.value = item.getAttribute('data-sql');
                    editor.focus();
                });
            })();
        </script>
        HTML;

    if ($results === [] && $error === null) {
        return $form;
    }

    $output = '';
    $timing = $elapsedMs !== null ? $elapsedMs . 'ms total' : '';
    $multi = count($results) > 1;

    foreach ($results as $index => $entry) {
        $label = $multi ? '<code class="lanter-sql-label">' . htmlspecialchars(mb_substr(preg_replace('/\s+/', ' ', $entry['sql']), 0, 80)) . '</code>' : '';

        if ($entry['result'] === null) {
            $output .= '<div class="lanter-sql-error">' . $label . htmlspecialchars((string) $error) . '</div>';
            continue;
        }

        $result = $entry['result'];

        if ($result['columns'] === []) {
            $output .= '<p class="lanter-sql-meta">' . $label . $result['affected'] . ' row(s) affected</p>';
            continue;
        }

        $exportButtons = lanter_sql_is_read_only($entry['sql'])
            ? '<form method="post" action="?action=sql_export" class="lanter-inline-form">' . $csrf
                . '<input type="hidden" name="sql" value="' . htmlspecialchars($entry['sql']) . '">'
                . '<button class="lanter-btn lanter-btn-ghost lanter-btn-small" type="submit" name="format" value="csv">' . lanter_icon('download') . '<span>CSV</span></button>'
                . '<button class="lanter-btn lanter-btn-ghost lanter-btn-small" type="submit" name="format" value="json">' . lanter_icon('download') . '<span>JSON</span></button>'
                . '</form>'
            : '';

        $head = '<tr>' . implode('', array_map(
            static fn (string $c): string => '<th>' . htmlspecialchars($c) . '</th>',
            $result['columns']
        )) . '</tr>';

        $body = '';
        foreach ($result['rows'] as $row) {
            $body .= '<tr>';
            foreach ($row as $value) {
                $body .= lanter_render_cell($value, null);
            }
            $body .= '</tr>';
        }

        $output .= '<div class="lanter-sql-meta lanter-sql-meta-row">' . $label . '<span>' . count($result['rows']) . ' row(s) returned</span>' . $exportButtons . '</div>'
            . '<div class="lanter-panel lanter-grid-panel"><table class="lanter-table"><thead>' . $head . '</thead><tbody>' . $body . '</tbody></table></div>';
    }

    if ($error !== null && ($results === [] || end($results)['result'] !== null)) {
        $output .= '<div class="lanter-sql-error">' . htmlspecialchars($error) . '</div>';
    }

    $timingHtml = $timing !== '' ? '<p class="lanter-sql-meta">' . $timing . '</p>' : '';

    return $form . $timingHtml . $output;
}
